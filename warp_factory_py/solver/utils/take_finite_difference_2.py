import numpy as np

def take_finite_difference_2(A, k_1, k_2, delta, phi_phi_flag):

    if is_gpu_array(A):
        delta = gpu_array(delta)

        s = gpu_array(A.shape)
        B = np.zeros(s, 'gpu_array')
    
    else:
        s = A.shape
        B = np.zeros(s)     

    if s[k_1] >= 5 and s[k_2] >= 5:
        if k_1 == k_2:
            match k_1:
                case 1:
                    B[2:-2, :, :, :] = (-(A[4:, :, :, :]-A[:-4, :, :, :]) + 16 * (A[3:-1, :, :, :] - A[1:-3, :, :, :]) - 30 * A[2:-2, :, :, :]) / (12 * (delta[k_1] ** 2))
                    B[0, :, :, :] = B[2, :, :, :]
                    B[1, :, :, :] = B[2, :, :, :]
                    B[-2, :, :, :] = B[-3, :, :, :]
                    B[-1, :, :, :] = B[-3, :, :, :]
                case 2:
                    B[:, 2:-2, :, :] = (-(A[:, 4:, :, :]-A[:, :-4, :, :]) + 16 * (A[:, 3:-1, :, :] - A[:, 1:-3, :, :]) - 30 * A[:, 2:-2, :, :]) / (12 * (delta[k_1] ** 2))
                    B[:, 0, :, :] = B[:, 2, :, :]
                    B[:, 1, :, :] = B[:, 2, :, :]
                    B[:, -2, :, :] = B[:, -3, :, :]
                    B[:, -1, :, :] = B[:, -3, :, :]
                case 3:
                    B[:, :, 2:-2, :] = (-(A[:, :, 4:, :]-A[:, :, :-4, :]) + 16 * (A[:, :, 3:-1, :] - A[:, :, 1:-3, :]) - 30 * A[:, :, 2:-2, :]) / (12 * (delta[k_1] ** 2))
                    if phi_phi_flag:
                        B[:, :, 0, :] = -2
                        B[:, :, 1, :] = -2
                        B[:, :, -2, :] = 2 
                        B[:, :, -1, :] = 2 
                    else:
                        B[:, :, -2, :] = B[:, :, -3, :]
                        B[:, :, -1, :] = B[:, :, -3, :]
                        B[:, :, 0, :] = B[:, :, 2, :]
                        B[:, :, 1, :] = B[:, :, 2, :]
                case 4:
                    B[:, :, :, 2:-2] = (-(A[:, :, :, 4:]-A[:, :, :, :-4]) + 16 * (A[:, :, :, 3:-1] - A[:, :, :, 1:-3]) - 30 * A[:, :, :, 2:-2]) / (12 * (delta[k_1] ** 2))
                    B[:, :, :, 0] = B[:, :, :, 2]
                    B[:, :, :, 1] = B[:, :, :, 2]
                    B[:, :, :, -2] = B[:, :, :, -3]
                    B[:, :, :, -1] = B[:, :, :, -3]

    return B